import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { expect, it, vi } from 'vitest';
import { translations } from '@/i18n';
import type { Dialogue } from '@/types';
import { Sidebar } from './index';
vi.mock('@/hooks/useApp', () => ({ useApp: () => ({ t: translations.ru, lang: 'ru' }) }));
const dialogue = (id: string, pinnedDate?: string, isArchived = false): Dialogue => ({ id, conversationId: id, benchmarkName: id, benchmarkNameEn: id, startedAt: '', updatedAt: `2026-10-${id === 'history' ? '30' : '29'}T10:00:00Z`, status: 'interview', messages: [], phase: 'recommend', pinnedDate, isArchived });
const props = () => ({ dialogues: [dialogue('history'), dialogue('pinned-old', '2026-10-28T10:00:00Z'), dialogue('pinned-new', '2026-10-29T10:00:00Z')], onLoadMore: vi.fn().mockResolvedValue(undefined), hasMore: false, isLoadingMore: false, onLoadMoreArchived: vi.fn().mockResolvedValue(undefined), hasMoreArchived: false, isLoadingMoreArchived: false, archivedTotal: 0, activeId: 'history', onNewSession: vi.fn(), onSelectDialogue: vi.fn(), onTogglePin: vi.fn(), onDeleteDialogue: vi.fn().mockResolvedValue(undefined), deriveDisplayStatus: () => 'draft' as const, mobileOpen: false, onToggleMobile: vi.fn(), onCloseMobile: vi.fn() });
it('keeps exact history DOM, pinned order, pin actions, and keyboard activation without a false delete action', () => {
  const values = props(); const { container } = render(<Sidebar {...values} />);
  expect(container.querySelector('.cr-side > .cr-side-head + .chats')).toBeInTheDocument();
  expect([...container.querySelectorAll('.chat-item > b')].map(item => item.textContent)).toEqual(['pinned-new', 'pinned-old', 'history']);
  const history = container.querySelector<HTMLElement>('.chat-item[data-id="history"]')!;
  fireEvent.keyDown(history, { key: 'Enter' });
  expect(values.onSelectDialogue).toHaveBeenCalledWith('history');
  values.onSelectDialogue.mockClear();
  fireEvent.click(screen.getByRole('button', { name: 'Закрепить чат «history»' }));
  expect(values.onTogglePin).toHaveBeenCalledWith('history');
  expect(values.onSelectDialogue).not.toHaveBeenCalled();
  const remove = screen.getByRole('button', { name: 'Удалить чат «history»' });
  expect(remove).toBeEnabled();
  fireEvent.click(remove);
  expect(values.onSelectDialogue).not.toHaveBeenCalled();
  expect(screen.getByRole('dialog', { name: 'Удалить чат?' })).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Отмена' }));
  expect(values.onDeleteDialogue).not.toHaveBeenCalled();
  expect(screen.queryByText(/Архивированные/)).not.toBeInTheDocument();
});
it('preserves paginated history with one pending load at a time', async () => {
  const values = props(); values.hasMore = true;
  let resolve!: () => void;
  values.onLoadMore.mockImplementation(() => new Promise<void>(done => { resolve = done; }));
  const { container } = render(<Sidebar {...values} />);
  const chats = container.querySelector('.chats')!;
  fireEvent.scroll(chats); fireEvent.scroll(chats);
  expect(values.onLoadMore).toHaveBeenCalledTimes(1);
  resolve(); await waitFor(() => expect(values.onLoadMore).toHaveBeenCalledTimes(1));
});
it('keeps the item on delete error and retries only after another confirmation', async () => {
  const values = props(); values.onDeleteDialogue.mockRejectedValueOnce(new Error('private server error')).mockResolvedValueOnce(undefined);
  render(<Sidebar {...values} />);
  fireEvent.click(screen.getByRole('button', { name: 'Удалить чат «history»' }));
  expect(screen.getByRole('button', { name: 'Отмена' })).toHaveFocus();
  fireEvent.keyDown(document, { key: 'Tab', shiftKey: true });
  expect(screen.getByRole('button', { name: 'Удалить' })).toHaveFocus();
  fireEvent.click(screen.getByRole('button', { name: 'Удалить' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Не удалось удалить чат');
  expect(screen.getByText('history')).toBeInTheDocument();
  expect(values.onDeleteDialogue).toHaveBeenCalledExactlyOnceWith('history');
  fireEvent.click(screen.getByRole('button', { name: 'Удалить' }));
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument());
  expect(values.onDeleteDialogue).toHaveBeenCalledTimes(2);
});
it('allows pinned and archived items to use the same confirmed delete action', async () => {
  const values = props(); values.dialogues.push(dialogue('archived', undefined, true)); values.archivedTotal = 1;
  render(<Sidebar {...values} />);
  fireEvent.click(screen.getByRole('button', { name: 'Удалить чат «pinned-new»' }));
  fireEvent.click(screen.getByRole('button', { name: 'Удалить' }));
  await waitFor(() => expect(values.onDeleteDialogue).toHaveBeenCalledWith('pinned-new'));
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument());
  fireEvent.click(screen.getByText('Архивированные чаты (1)'));
  const archive = screen.getByText('Архивированные чаты (1)').closest('details')!;
  archive.open = true; fireEvent(archive, new Event('toggle'));
  fireEvent.click(await screen.findByRole('button', { name: 'Удалить чат «archived»' }));
  fireEvent.click(screen.getByRole('button', { name: 'Удалить' }));
  await waitFor(() => expect(values.onDeleteDialogue).toHaveBeenCalledWith('archived'));
});
it('preserves the chosen delete action through a sidebar refresh and contains outside focus', async () => {
  const values = props();
  const view = (dialogues: Dialogue[]) => <><Sidebar {...values} dialogues={dialogues} /><input aria-label="Основной чат" /></>;
  const { rerender } = render(view(values.dialogues));
  const opener = screen.getByRole('button', { name: 'Удалить чат «history»' });
  opener.focus(); fireEvent.click(opener);
  const confirm = screen.getByRole('button', { name: 'Удалить' });
  confirm.focus();
  rerender(view([...values.dialogues, dialogue('new-chat')]));
  expect(confirm).toHaveFocus();
  screen.getByRole('textbox', { name: 'Основной чат' }).focus();
  expect(screen.getByRole('button', { name: 'Отмена' })).toHaveFocus();
  let finish!: () => void;
  values.onDeleteDialogue.mockImplementationOnce(() => new Promise<void>(resolve => { finish = resolve; }));
  fireEvent.click(confirm);
  expect(screen.getByRole('dialog', { name: 'Удалить чат?' })).toHaveFocus();
  screen.getByRole('textbox', { name: 'Основной чат' }).focus();
  expect(screen.getByRole('dialog', { name: 'Удалить чат?' })).toHaveFocus();
  fireEvent.keyDown(document, { key: 'Tab' });
  expect(screen.getByRole('dialog', { name: 'Удалить чат?' })).toHaveFocus();
  await act(async () => finish());
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument());
  expect(opener).toHaveFocus();
});
